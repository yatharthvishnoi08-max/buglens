import { test, expect } from "@playwright/test";
import { mkdir, readFile } from "node:fs/promises";
test("sample screenshot to validated Markdown, keyboard and mobile", async ({ page }, info) => {
  const errors: string[] = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await page.keyboard.press("Tab"); await expect(page.getByRole("link", { name: "Skip to content" })).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("heading", { name: /Check your GitHub code/ })).toBeVisible();
  await expect(page.locator(".hero-description")).toContainText("Get a detailed report, fix instructions and ready-to-use prompts for your coding assistant.");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await mkdir("docs/screenshots", { recursive: true });
  await page.screenshot({ path: `docs/screenshots/${info.project.name}-landing.png`, fullPage: true });
  await page.getByRole("link", { name: "Try the sample bug" }).click();
  await expect(page.locator(".mode-bar .badge")).toContainText("Synthetic fixture mode");
  await expect(page.locator(".mode-bar .badge")).toBeVisible();
  await expect(page.getByLabel("Expected behavior", { exact: false })).toHaveValue(/Both checkout actions/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  const submit = page.getByRole("button", { name: "Generate issue draft" });
  const box = await submit.boundingBox(); expect(box!.height).toBeGreaterThanOrEqual(44);
  await submit.focus(); await page.keyboard.press("Enter");
  await expect(page).toHaveURL(/\/result$/);
  await expect(page.getByRole("status").filter({ hasText: "Issue draft validated" })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Ready for a human review." })).toBeFocused();
  await expect.poll(() => page.getByRole("heading", { name: "Ready for a human review." }).evaluate((node) => {
    const bounds = node.getBoundingClientRect();
    return bounds.top >= 0 && bounds.bottom <= window.innerHeight;
  })).toBe(true);
  await expect(page.getByText("Synthetic fixture mode", { exact: true })).toBeVisible();
  await expect(page.getByRole("article", { name: "Compiled issue" })).toContainText("Observed visual evidence");
  await expect(page.getByRole("article", { name: "Compiled issue" })).toContainText("Suspected causes — not verified");
  await expect(page.getByRole("article", { name: "Compiled issue" })).toContainText("CheckoutActions.tsx");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: `docs/screenshots/${info.project.name}-result.png`, fullPage: true });
  await page.screenshot({ path: `docs/screenshots/${info.project.name}-result-viewport.png` });
  const downloadEvent = page.waitForEvent("download"); await page.getByRole("button", { name: "Download Markdown" }).click();
  const download = await downloadEvent; expect(download.suggestedFilename()).toBe("buglens-issue.md");
  const file = await download.path(); expect(await readFile(file!, "utf8")).toContain("SYNTHETIC FIXTURE MODE");
  expect(await page.evaluate(() => localStorage.length + sessionStorage.length)).toBe(0);
  await page.reload(); await expect(page.getByRole("heading", { name: "Start with your repository." })).toBeVisible();
  expect(errors).toEqual([]);
});
